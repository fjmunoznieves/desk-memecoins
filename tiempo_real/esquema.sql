CREATE TABLE IF NOT EXISTS det (mint TEXT PRIMARY KEY, billetera TEXT, ts_tx INTEGER, ts_det INTEGER, firma TEXT, fuente TEXT, sym TEXT, precio TEXT, mc INTEGER, liq INTEGER, pool TEXT, creado INTEGER);
CREATE INDEX IF NOT EXISTS det_ts ON det(ts_det);
CREATE TABLE IF NOT EXISTS muestra (id INTEGER PRIMARY KEY, ts INTEGER, cuerpo TEXT);
CREATE TABLE IF NOT EXISTS stats (k TEXT PRIMARY KEY, n INTEGER, ts INTEGER);
CREATE TABLE IF NOT EXISTS ult (w TEXT PRIMARY KEY, sig TEXT, ts INTEGER);
CREATE TABLE IF NOT EXISTS velas (mint TEXT, ts INTEGER, precio TEXT, mc INTEGER, liq INTEGER, b5 INTEGER, s5 INTEGER, v5 INTEGER, PRIMARY KEY (mint, ts));
CREATE TABLE IF NOT EXISTS ventas (mint TEXT, w TEXT, ts INTEGER, vendido REAL, antes REAL, firma TEXT PRIMARY KEY);
